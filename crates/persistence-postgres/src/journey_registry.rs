pub fn resolver_registry_is_closed() -> bool {
    JOURNEY_EDGE_RESOLVERS.len() == JOURNEY_EDGE_RESOLVER_COUNT
        && JOURNEY_EDGE_RESOLVERS
            .windows(2)
            .all(|rows| rows[0].edge_id < rows[1].edge_id)
}

